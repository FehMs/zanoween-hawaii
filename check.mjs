import fs from 'node:fs';
import assert from 'node:assert/strict';
const html = fs.readFileSync('dist/index.html', 'utf8');
const ids = [...html.matchAll(/id="([^"]+)"/g)].map(match => match[1]);
assert.equal(ids.length, new Set(ids).size, 'IDs must be unique');
for (const match of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(match[1]), `Missing anchor ${match[1]}`);
for (const path of ['dist/assets/tropical-night.png', 'dist/assets/favicon.svg', 'dist/style.css', 'dist/app.js']) assert(fs.existsSync(path), `Missing asset ${path}`);
assert(html.includes('Espaço Limão'));
assert(html.includes('após a compra'));
assert(html.includes('Os ingressos ainda não estão à venda.'));
const script = fs.readFileSync('dist/app.js', 'utf8');
const handlers = {};
let calendarBlob;
const element = () => ({addEventListener(name, handler) { this[name] = handler; }, classList:{add(){},remove(){}}, showModal(){this.open=true}, close(){this.open=false}});
const modal = element(), close = element(), ticket = element(), calendar = element(), toast = element(), share = element();
const mockDocument = {querySelector(selector){ return {'#tickets':modal,'.close-modal':close,'.toast':toast,'#share':share}[selector]; },querySelectorAll(selector){return selector === '.ticket-trigger' ? [ticket] : [calendar]}, createElement(){return {click(){handlers.download=this.download}}}};
const mockURL = {createObjectURL(blob){calendarBlob=blob;return 'blob:test'},revokeObjectURL(){}};
new Function('document','URL','Blob','setTimeout','clearTimeout','navigator','location',script)(mockDocument,mockURL,Blob,() => 1,() => {},{}, {href:'https://example.com'});
ticket.click(); assert.equal(modal.open,true);
close.click(); assert.equal(modal.open,false);
calendar.click(); assert.equal(handlers.download,'zanoween-hawaii-2026.ics');
